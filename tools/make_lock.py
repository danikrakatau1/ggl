"""Build a fully pinned, hashed requirements lock from the current venv.

Downloads every pinned distribution, hashes the artifact, and emits
`requirements.lock` for `pip install --require-hashes`.

The lock is platform- and Python-version-specific (wheels), which is the point:
a rebuild either matches byte-for-byte or fails loudly.
"""

from __future__ import annotations

import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENV = ROOT / ".venv"
PY = VENV / "bin" / "python"
WHEELHOUSE = ROOT / ".wheelhouse"
LOCK = ROOT / "requirements.lock"


def pinned() -> list[str]:
    out = subprocess.run(
        [str(PY), "-m", "pip", "list", "--format=freeze"],
        capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    return [line for line in out if "==" in line and not line.startswith("pip==")]


def main() -> int:
    if WHEELHOUSE.exists():
        shutil.rmtree(WHEELHOUSE)
    WHEELHOUSE.mkdir()

    packages = pinned()
    for spec in packages:
        proc = subprocess.run(
            [str(PY), "-m", "pip", "download", "--only-binary=:all:", "--no-deps",
             "-d", str(WHEELHOUSE), spec],
            capture_output=True, text=True,
        )
        if proc.returncode != 0:
            print(f"FAIL download {spec}\n{proc.stderr[-500:]}", file=sys.stderr)
            return 1

    lines = []
    for artifact in sorted(WHEELHOUSE.iterdir()):
        digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
        # "name-1.2.3-py3-none-any.whl" -> name==1.2.3
        name_version = artifact.name.split("-py")[0].split("-cp")[0]
        name, _, version = name_version.partition("-")
        if "-" in version:  # versions with local build tags
            version = version.split("-")[0]
        lines.append(f"{name}=={version} --hash=sha256:{digest}")

    LOCK.write_text(
        "# generated by tools/make_lock.py — do not edit by hand\n"
        "# platform: darwin-arm64 / py3.13 / official PyPI\n"
        + "\n".join(lines) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {LOCK} with {len(lines)} pinned artifacts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
